/**
 * Generates src/lib/database.types.ts from the real migrations.
 *
 * Applies supabase/migrations to an in-process Postgres (PGlite) and
 * introspects the resulting `public` schema, emitting types in the same shape
 * as `supabase gen types typescript`, so the Supabase client is fully typed
 * without Docker or a linked project.
 *
 * Once a Supabase project is linked you can equivalently run:
 *   npx supabase gen types typescript --linked --schema public > src/lib/database.types.ts
 *
 * Usage: npm run db:types   (or `npm run db:types -- --check` in CI)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createDatabase } from '../tests/db/harness.ts'

const outFile = fileURLToPath(new URL('../src/lib/database.types.ts', import.meta.url))
const db = await createDatabase()

type Column = {
  table_name: string
  column_name: string
  udt_name: string
  data_type: string
  is_nullable: 'YES' | 'NO'
  column_default: string | null
  is_identity: 'YES' | 'NO'
}

const enums = (
  await db.query<{ name: string; values: string[] }>(`
    select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as values
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows

const enumNames = new Set(enums.map((e) => e.name))

const tables = (
  await db.query<{ table_name: string }>(`
    select table_name from information_schema.tables
    where table_schema = 'public' and table_type = 'BASE TABLE' order by table_name`)
).rows.map((r) => r.table_name)

const columns = (
  await db.query<Column>(`
    select table_name, column_name, udt_name, data_type, is_nullable, column_default, is_identity
    from information_schema.columns where table_schema = 'public'
    order by table_name, ordinal_position`)
).rows

const foreignKeys = (
  await db.query<{
    name: string
    table_name: string
    columns: string[]
    ref_table: string
    ref_columns: string[]
    one_to_one: boolean
  }>(`
    select c.conname as name, cl.relname as table_name,
      array(select a.attname from unnest(c.conkey) with ordinality k(n, i)
            join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.n order by k.i) as columns,
      rcl.relname as ref_table,
      array(select a.attname from unnest(c.confkey) with ordinality k(n, i)
            join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.n order by k.i) as ref_columns,
      exists (select 1 from pg_constraint u where u.conrelid = c.conrelid and u.contype in ('p', 'u')
              and u.conkey::int[] @> c.conkey::int[] and u.conkey::int[] <@ c.conkey::int[]) as one_to_one
    from pg_constraint c
    join pg_class cl on cl.oid = c.conrelid
    join pg_namespace n on n.oid = cl.relnamespace
    join pg_class rcl on rcl.oid = c.confrelid
    join pg_namespace rn on rn.oid = rcl.relnamespace
    where c.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
    order by cl.relname, c.conname`)
).rows

const functions = (
  await db.query<{ name: string; arg_names: string[] | null; arg_types: string[]; return_type: string }>(`
    select p.proname as name, p.proargnames as arg_names,
      array(select t.typname from unnest(p.proargtypes) with ordinality a(oid, i)
            join pg_type t on t.oid = a.oid order by a.i) as arg_types,
      rt.typname as return_type
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and rt.typname <> 'trigger'
    order by p.proname`)
).rows

function tsType(udt: string): string {
  if (udt.startsWith('_')) {
    const inner = tsType(udt.slice(1))
    return inner.includes(' ') ? `(${inner})[]` : `${inner}[]`
  }
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`
  switch (udt) {
    case 'int2': case 'int4': case 'int8': case 'float4': case 'float8': case 'numeric':
      return 'number'
    case 'bool':
      return 'boolean'
    case 'json': case 'jsonb':
      return 'Json'
    case 'void':
      return 'undefined'
    default:
      return 'string'
  }
}

const q = (s: string) => JSON.stringify(s)
const lines: string[] = []
const push = (indent: number, text: string) => lines.push('  '.repeat(indent) + text)

lines.push(
  '// This file is generated by scripts/gen-db-types.ts from supabase/migrations.',
  '// Do not edit by hand — run `npm run db:types` after changing the schema.',
  '',
  'export type Json =',
  '  | string',
  '  | number',
  '  | boolean',
  '  | null',
  '  | { [key: string]: Json | undefined }',
  '  | Json[]',
  '',
  'export type Database = {',
  '  __InternalSupabase: {',
  '    PostgrestVersion: "13"',
  '  }',
  '  public: {',
  '    Tables: {',
)

for (const table of tables) {
  const cols = columns.filter((c) => c.table_name === table)
  push(3, `${table}: {`)
  for (const kind of ['Row', 'Insert', 'Update'] as const) {
    push(4, `${kind}: {`)
    for (const c of cols) {
      const nullable = c.is_nullable === 'YES'
      const base = tsType(c.udt_name) + (nullable ? ' | null' : '')
      const optional =
        kind === 'Update' ||
        (kind === 'Insert' && (nullable || c.column_default !== null || c.is_identity === 'YES'))
      push(5, `${c.column_name}${optional ? '?' : ''}: ${base}`)
    }
    push(4, '}')
  }
  const fks = foreignKeys.filter((f) => f.table_name === table)
  if (fks.length === 0) {
    push(4, 'Relationships: []')
  } else {
    push(4, 'Relationships: [')
    for (const fk of fks) {
      push(5, '{')
      push(6, `foreignKeyName: ${q(fk.name)}`)
      push(6, `columns: [${fk.columns.map(q).join(', ')}]`)
      push(6, `isOneToOne: ${fk.one_to_one}`)
      push(6, `referencedRelation: ${q(fk.ref_table)}`)
      push(6, `referencedColumns: [${fk.ref_columns.map(q).join(', ')}]`)
      push(5, '},')
    }
    push(4, ']')
  }
  push(3, '}')
}
push(2, '}')
push(2, 'Views: {')
push(3, '[_ in never]: never')
push(2, '}')
push(2, 'Functions: {')
for (const fn of functions) {
  push(3, `${fn.name}: {`)
  if (fn.arg_types.length === 0) {
    push(4, 'Args: never')
  } else {
    push(4, 'Args: {')
    fn.arg_types.forEach((t, i) => push(5, `${fn.arg_names?.[i] ?? `arg${i}`}: ${tsType(t)}`))
    push(4, '}')
  }
  push(4, `Returns: ${tsType(fn.return_type)}`)
  push(3, '}')
}
push(2, '}')
push(2, 'Enums: {')
for (const e of enums) push(3, `${e.name}: ${e.values.map(q).join(' | ')}`)
push(2, '}')
push(2, 'CompositeTypes: {')
push(3, '[_ in never]: never')
push(2, '}')
push(1, '}')
lines.push('}', '')

lines.push(
  'type PublicSchema = Database["public"]',
  '',
  'export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]',
  'export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]',
  'export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]',
  'export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]',
  '',
  'export const Constants = {',
  '  public: {',
  '    Enums: {',
  ...enums.map((e) => `      ${e.name}: [${e.values.map(q).join(', ')}],`),
  '    },',
  '  },',
  '} as const',
  '',
)

const output = lines.join('\n')
await db.close()

if (process.argv.includes('--check')) {
  const current = readFileSync(outFile, 'utf8')
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error('database.types.ts is out of date — run `npm run db:types`.')
    process.exit(1)
  }
  console.log('database.types.ts is up to date.')
} else {
  writeFileSync(outFile, output)
  console.log(`Wrote ${outFile}`)
}
